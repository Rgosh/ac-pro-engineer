//! The engineer's radio lines, in the shape the voice bank reads.
//!
//!     cargo run -p ac_core --example radio_lines > tools/voicebank/lines/en.tsv
//!
//! `radio::lines::LINES` is the script; this prints it as `key, style, text`
//! with a fourth column for a line that carries a value, so the voice bank
//! speaks exactly what the radio can ask for — nothing written twice.

use ac_core::radio::lines::LINES;

fn main() {
    println!("# GENERATED by `cargo run -p ac_core --example radio_lines` from");
    println!("# core/src/radio/lines.rs — edit the lines there, not here.");
    println!("# key\tstyle\ttext\tvalues");
    for line in LINES {
        let said = line.said;
        match line.values {
            Some((low, high)) => println!(
                "{}.{{n}}\t{}\t{said}\tn={low}..{high}",
                line.id,
                line.style.name()
            ),
            None => println!("{}\t{}\t{said}", line.id, line.style.name()),
        }
    }
}
